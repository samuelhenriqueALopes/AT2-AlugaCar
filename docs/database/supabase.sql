-- =============================================================================
-- AlugaCar - configuracao do banco no Supabase (PostgreSQL)
--
-- Como usar: Supabase > SQL Editor > New query > cole este arquivo > Run.
-- O script pode ser executado mais de uma vez (idempotente).
--
-- Observacao: o back-end tambem cria/atualiza as tabelas sozinho ao iniciar
-- (spring.jpa.hibernate.ddl-auto=update). Este script documenta o modelo fisico
-- e aplica as restricoes de seguranca especificas do Supabase.
-- =============================================================================

-- 1) Schema dedicado ----------------------------------------------------------
-- O Supabase expoe o schema "public" automaticamente na Data API (REST/GraphQL),
-- acessivel com a chave publica (anon). As tabelas do AlugaCar ficam no schema
-- "alugacar", que nao e exposto: o acesso aos dados acontece somente pelo
-- back-end Spring Boot, que aplica autenticacao e regras de negocio.
create schema if not exists alugacar;

-- 2) Tabelas (modelo fisico gerado a partir das entidades JPA) -----------------
create table if not exists alugacar.usuarios (
    id      bigint generated by default as identity primary key,
    nome    varchar(120) not null,
    login   varchar(60)  not null unique,
    senha   varchar(255) not null,            -- hash BCrypt
    email   varchar(120)
);

create table if not exists alugacar.agentes (
    id      bigint primary key,
    cnpj    varchar(18) not null unique,
    tipo    varchar(10) not null check (tipo in ('EMPRESA', 'BANCO')),
    constraint FKs13ghxyh78s7qjsn9jni4drm9 foreign key (id) references alugacar.usuarios
);

create table if not exists alugacar.clientes (
    id        bigint primary key,
    rg        varchar(20)  not null unique,
    cpf       varchar(14)  not null unique,
    endereco  varchar(255) not null,
    profissao varchar(80),
    constraint FKl8la8bmm5w5vtntkh5bhv5y41 foreign key (id) references alugacar.usuarios
);

create table if not exists alugacar.rendimentos (
    id                   bigint generated by default as identity primary key,
    cliente_id           bigint not null,
    entidade_empregadora varchar(120) not null,
    valor                numeric(12, 2) not null,
    constraint FKnpebmbf623cluot2bys5g8eah foreign key (cliente_id) references alugacar.clientes
);

create table if not exists alugacar.automoveis (
    id              bigint generated by default as identity primary key,
    matricula       varchar(30) not null unique,
    ano             integer     not null,
    marca           varchar(60) not null,
    modelo          varchar(60) not null,
    placa           varchar(10) not null unique,
    imagem          text,                      -- caminho publico ou data URL
    proprietario_id bigint,
    constraint FKtrdixym7vqlfe6ur07q69vvo7 foreign key (proprietario_id) references alugacar.usuarios
);

create table if not exists alugacar.pedidos_aluguel (
    id                  bigint generated by default as identity primary key,
    cliente_id          bigint not null,
    automovel_id        bigint not null,
    data_inicio         date not null,
    data_fim            date not null,
    data_criacao        timestamp(6) not null,
    status              varchar(15) not null
                        check (status in ('PENDENTE', 'APROVADO', 'REPROVADO', 'CANCELADO', 'CONTRATADO')),
    observacoes         varchar(500),
    solicita_credito    boolean not null,
    agente_avaliador_id bigint,
    parecer             varchar(500),
    data_avaliacao      timestamp(6),
    constraint FKi3sdiedfs0e29f9dyiw9lqaf1 foreign key (cliente_id) references alugacar.clientes,
    constraint FK5k9ef2y2ceke4jeuxifqklxrv foreign key (automovel_id) references alugacar.automoveis,
    constraint FKeikisataqsevgijd8jrta23ql foreign key (agente_avaliador_id) references alugacar.agentes
);

create table if not exists alugacar.contratos_credito (
    id                bigint generated by default as identity primary key,
    banco_id          bigint not null,
    valor             numeric(12, 2) not null,
    taxa_juros_mensal numeric(6, 3)  not null,
    numero_parcelas   integer        not null,
    constraint FKpyfs8my1yq56kxmt88brko8h4 foreign key (banco_id) references alugacar.agentes
);

create table if not exists alugacar.contratos (
    id                  bigint generated by default as identity primary key,
    pedido_id           bigint not null unique,
    agente_id           bigint not null,
    tipo_propriedade    varchar(10) not null check (tipo_propriedade in ('CLIENTE', 'EMPRESA', 'BANCO')),
    data_assinatura     timestamp(6) not null,
    contrato_credito_id bigint unique,
    constraint FKfn7uxupkd5kxsfjjoqa5d4250 foreign key (pedido_id) references alugacar.pedidos_aluguel,
    constraint FKr6p4kql2y3acw36ui6cnshdeo foreign key (agente_id) references alugacar.agentes,
    constraint FK69nqagbkm3fxsm0j5fdfo06m1 foreign key (contrato_credito_id) references alugacar.contratos_credito
);

-- 3) Indices nas chaves estrangeiras (consultas por cliente, automovel e agente)
create index if not exists idx_rendimentos_cliente      on alugacar.rendimentos (cliente_id);
create index if not exists idx_automoveis_proprietario  on alugacar.automoveis (proprietario_id);
create index if not exists idx_pedidos_cliente          on alugacar.pedidos_aluguel (cliente_id);
create index if not exists idx_pedidos_automovel_status on alugacar.pedidos_aluguel (automovel_id, status);
create index if not exists idx_pedidos_agente           on alugacar.pedidos_aluguel (agente_avaliador_id);
create index if not exists idx_credito_banco            on alugacar.contratos_credito (banco_id);
create index if not exists idx_contratos_agente         on alugacar.contratos (agente_id);

-- 4) Seguranca: bloqueia os papeis da Data API do Supabase ---------------------
-- "anon" e "authenticated" sao os papeis usados pela API publica do Supabase.
-- Nenhum deles deve enxergar o schema do AlugaCar.
revoke all on schema alugacar from public, anon, authenticated;
revoke all on all tables    in schema alugacar from public, anon, authenticated;
revoke all on all sequences in schema alugacar from public, anon, authenticated;
alter default privileges in schema alugacar revoke all on tables    from public, anon, authenticated;
alter default privileges in schema alugacar revoke all on sequences from public, anon, authenticated;

-- Defesa em profundidade: RLS ativo e sem politicas = nenhum acesso via API.
-- O back-end conecta como dono das tabelas (postgres), que nao e afetado pelo RLS.
alter table alugacar.usuarios          enable row level security;
alter table alugacar.agentes           enable row level security;
alter table alugacar.clientes          enable row level security;
alter table alugacar.rendimentos       enable row level security;
alter table alugacar.automoveis        enable row level security;
alter table alugacar.pedidos_aluguel   enable row level security;
alter table alugacar.contratos_credito enable row level security;
alter table alugacar.contratos         enable row level security;

